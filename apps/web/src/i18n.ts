type TranslationKey = keyof typeof translations.vi

export function t(key: TranslationKey | string, params?: Record<string, string | number>): string {
  const locale = getLocale()
  const dict = translations[locale] || translations.vi
  let text = (dict as Record<string, string>)[key] || (translations.vi as Record<string, string>)[key] || key
  if (params) {
    for (const [paramKey, paramVal] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramVal))
    }
  }
  return text
}

