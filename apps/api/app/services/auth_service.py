"""Legacy scrypt password hashing.

The application hashes new passwords with argon2id (``app.auth``) and upgrades an old scrypt hash on the next sign-in.
These two functions remain so tests can create legacy-format hashes; nothing in the request path calls them.
"""

import base64
import hashlib
import hmac
import secrets


def _b64(value: bytes) -> str:
    return base64.urlsafe_b64encode(value).rstrip(b"=").decode("ascii")


def _unb64(value: str) -> bytes:
    return base64.urlsafe_b64decode(value + "=" * (-len(value) % 4))


def hash_password(password: str) -> str:
    salt = secrets.token_bytes(16)
    digest = hashlib.scrypt(password.encode("utf-8"), salt=salt, n=2**14, r=8, p=1, dklen=64)
    return f"scrypt$16384$8$1${_b64(salt)}${_b64(digest)}"


def verify_password(password: str, encoded: str | None) -> bool:
    if not encoded:
        return False
    try:
        algorithm, n, r, p, salt, expected = encoded.split("$")
        if algorithm != "scrypt":
            return False
        actual = hashlib.scrypt(password.encode("utf-8"), salt=_unb64(salt), n=int(n), r=int(r), p=int(p), dklen=64)
        return hmac.compare_digest(actual, _unb64(expected))
    except (ValueError, TypeError):
        return False
